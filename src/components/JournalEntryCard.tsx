import { Sparkles } from "lucide-react";
import { QUESTIONS } from "@/data/questionnaire";
import type { JournalEntry } from "@/lib/store";
import { formatSeconds } from "@/lib/hooks";
import { ChemicalBadge } from "./ChemicalBadge";

const STATUS_LABEL: Record<JournalEntry["status"], string> = {
  completed: "Completed",
  partial: "Partly done",
  attempted: "Attempted",
};

const dateFormat = new Intl.DateTimeFormat(undefined, {
  dateStyle: "medium",
  timeStyle: "short",
});

function answerLabel(questionId: string, value: string | number): string | null {
  const q = QUESTIONS.find((q) => q.id === questionId);
  if (!q) return null;
  if (q.kind === "scale") return `${value}/${q.max}`;
  return q.options.find((o) => o.value === value)?.label ?? null;
}

export function JournalEntryCard({ entry }: { entry: JournalEntry }) {
  const mood =
    entry.answers?.moodBefore !== undefined && entry.answers?.moodAfter !== undefined
      ? `Mood ${entry.answers.moodBefore} → ${entry.answers.moodAfter}`
      : null;
  const difficulty = entry.answers?.difficulty
    ? answerLabel("difficulty", entry.answers.difficulty)
    : null;

  return (
    <article className="space-y-2 rounded-2xl border bg-card p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <ChemicalBadge chemical={entry.chemical} />
        <time className="text-xs text-muted-foreground" dateTime={entry.completedAt}>
          {dateFormat.format(new Date(entry.completedAt))}
        </time>
      </div>
      <h3 className="flex items-center gap-1.5 font-semibold">
        {entry.title}
        {entry.source === "ai" && (
          <Sparkles className="size-3.5 text-muted-foreground" aria-label="Generated by Gemma" />
        )}
      </h3>
      <p className="text-sm text-muted-foreground">
        {STATUS_LABEL[entry.status]} · {entry.minutes} min outside
        {entry.screenSeconds > 0 && ` · ${formatSeconds(entry.screenSeconds)} screen peeks`}
        {mood && ` · ${mood}`}
        {difficulty && ` · ${difficulty}`}
      </p>
      {entry.reflection && (
        <blockquote className="border-l-2 pl-3 text-sm italic text-foreground/80">
          {entry.reflection}
        </blockquote>
      )}
      {entry.aiReflection && (
        <p className="rounded-lg bg-muted/60 p-3 text-sm">
          <span className="font-medium">Coach:</span> {entry.aiReflection}
        </p>
      )}
    </article>
  );
}
